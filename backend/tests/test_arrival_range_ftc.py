def test_t1_arrival_ranges_persona_ordered_by_tightness(arrival):
    """Done-condition (a): arrival ranges are persona-ordered by tightness —
    nit ⊂ (roughly) tag ⊂ maniac. Measured by kept-count: over the SAME dealt
    spots, a tighter preflop flat-calling range reaches the flop with strictly
    fewer hands. (A literal class-SUBSET is intentionally NOT asserted — nit
    and tag flat-call genuinely different STYLES, e.g. nit flats medium pairs
    the tag 3bets and vice-versa, so the ranges differ in composition, not just
    width; kept-count is the faithful tightness signal.) The maniac's range is
    the widest, containing the most classes."""
    n_nit = len(arrival.flop["nit"])
    n_tag = len(arrival.flop["tag"])
    n_maniac = len(arrival.flop["maniac"])
    assert n_nit < n_tag < n_maniac, (n_nit, n_tag, n_maniac)

    def n_classes(p):
        return len({hole_cards_to_class(*h) for h, _ in arrival.flop[p]})

    assert n_classes("nit") < n_classes("maniac"), (n_classes("nit"), n_classes("maniac"))


@pytest.mark.parametrize("persona", ALL_PERSONAS)
def test_t1_arrival_is_call_only_no_3bet_hands(arrival, persona):
    """Done-condition (b): the call-only proof — no hand class the persona
    3bets vs an RFI (pure-3bet: observed raising, never calling) appears in its
    arrival range."""
    arrival_classes = {hole_cards_to_class(*h) for h, _ in arrival.flop[persona]}
    assert arrival_classes.isdisjoint(arrival.pure_3bet_classes[persona]), (
        f"{persona}: 3bet hands leaked into arrival range: "
        f"{arrival_classes & arrival.pure_3bet_classes[persona]}"
    )


