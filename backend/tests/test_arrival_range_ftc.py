ALL_PERSONAS = sorted(v.value for v in VillainType)

# Mirror `test_personas_postflop.py::PRICE_FRACS` — one size per RES-E bucket
# (SMALL / MEDIUM / LARGE(pot) / OVERBET).
FLOP_FRACS = (0.33, 0.5, 1.0, 1.5)

# Sample size for the arrival sampler. >= the existing `_PRICE_N` (1250);
# bumped because the arrival filter is a SUBSET of the dealt spots and tight
# ranges (nit) keep only a sliver — the W3R-2 provability criterion is that the
# flop bands assert stably at this N across repeated seeds.
_ARRIVAL_N = 2500

# Canonical single-raised HU pot: RFI to 3bb, one flat call → ~6bb flop pot,
# each player ~97bb behind (100bb − 3bb preflop). The villain c-bets a FIXED
# 2/3-pot on every street to drive the continuation sim (T3).
_POT_FLOP = 6.0
_STACK_START = 97.0
_CONT_FRAC = 0.66

_DEAL_SEED = 20260721  # mirror the existing fixture's deal seed
# Position is a no-op for `vs_rfi` (all packs' nodes are `positions=None`
# wildcards) — the load-bearing setup is `facing="vs_rfi"` + the caller role.
_CALLER_POS = Position.BB


# --------------------------------------------------------------- legal helpers
# Local one-liners (no cross-import of the sibling test module's helpers).


def _lf() -> LegalAction:
    return LegalAction(action=ActionType.FOLD)


def _lc(amount: float) -> LegalAction:
    return LegalAction(action=ActionType.CALL, min_bb=amount)


def _lr(lo: float, hi: float) -> LegalAction:
    return LegalAction(action=ActionType.RAISE, min_bb=lo, max_bb=hi)


# --------------------------------------------------------------- spot dealing


def _deal_spots(n: int) -> list[tuple[tuple[str, str], list[str]]]:
    """Seed-pinned list of (hole, 5-card board). Same physical cards are reused
    across persona × size × street so range-composition variance cancels
    (paired sampling), exactly like the existing `fold_by_size` fixture."""
    deal_rng = random.Random(_DEAL_SEED)
    deck0 = [r + s for r in RANKS for s in "shdc"]
    spots = []
    for _ in range(n):
        deck = deck0[:]
        deal_rng.shuffle(deck)
        spots.append(((deck[0], deck[1]), deck[2:7]))  # hole + flop/turn/river
    return spots


# --------------------------------------------------------------- arrival ranges

Spot = tuple[tuple[str, str], list[str]]


class _Arrival:
    """Per-persona arrival ranges + the pure-3bet class set (for the call-only
    proof) + the per-street pot/stack the continuation sim resolves to."""

    def __init__(self) -> None:
        self.flop: dict[str, list[Spot]] = {}
        self.turn: dict[str, list[Spot]] = {}
        self.river: dict[str, list[Spot]] = {}
        self.pure_3bet_classes: dict[str, frozenset[str]] = {}
        # Uniform per-street pot/stack (call-only continuation on a uniform
        # starting pot ⇒ every continuing spot shares one trajectory).
        bet_f = round(_CONT_FRAC * _POT_FLOP, 2)
        self.pot_turn = _POT_FLOP + 2 * bet_f
        self.stack_turn = _STACK_START - bet_f
        bet_t = round(_CONT_FRAC * self.pot_turn, 2)
        self.pot_river = self.pot_turn + 2 * bet_t
        self.stack_river = self.stack_turn - bet_t


def _build_flop_arrival(pack, spots: list[Spot]) -> tuple[list[Spot], frozenset[str]]:
    """Replay the persona's `vs_rfi` preflop policy; keep flat-CALL hands only.

    Returns (kept spots, pure-3bet classes) where a pure-3bet class was observed
    raising (3bet/4bet/5bet) and NEVER calling — the call-only proof asserts
    those never leak into the arrival range.
    """
    rng = random.Random(999)
    kept: list[Spot] = []
    call_classes: set[str] = set()
    raise_classes: set[str] = set()
    for hole, board in spots:
        act = sample_preflop_action(pack, _CALLER_POS, "vs_rfi", hole, rng)
        cls = hole_cards_to_class(*hole)
        if act.name == "call":
            kept.append((hole, board))
            call_classes.add(cls)
        elif act.name in ("3bet", "4bet", "5bet_shove"):
            raise_classes.add(cls)
    return kept, frozenset(raise_classes - call_classes)


def _continues_call(pack, rng, hole, board_n, pot_pre, stack, street) -> bool:
    """True iff the persona flat-CALLS a fixed 2/3-pot c-bet on `board_n`.

    Continuation is CALL-ONLY by the same logic that makes the arrival range
    call-only (T1): a hand that RAISES becomes the aggressor and would be
    c-betting the next street, not facing a bet — counting it would pollute the
    DEFENDING range this harness measures. FOLD and RAISE both drop out.
    """
    bet = round(_CONT_FRAC * pot_pre, 2)
    d = sample_postflop_decision(
        pack, hole, board_n, [_lf(), _lc(bet), _lr(2 * bet, stack)],
        pot_pre + bet, stack, 1, rng, current_bet_to=bet, street=street,
    )
    return d.action is ActionType.CALL


@pytest.fixture(scope="module")
def arrival() -> _Arrival:
    packs = load_persona_packs()
    if set(VillainType) - set(packs):
        pytest.skip("not all persona packs authored yet")
    spots = _deal_spots(_ARRIVAL_N)
    a = _Arrival()
    for persona in ALL_PERSONAS:
        pack = packs[VillainType(persona)]
        flop, pure3 = _build_flop_arrival(pack, spots)
        a.flop[persona] = flop
        a.pure_3bet_classes[persona] = pure3
        # Turn range: flop arrivals that flat-call the flop c-bet.
        rng = random.Random(4001)
        turn = [
            s for s in flop
            if _continues_call(pack, rng, s[0], s[1][:3], _POT_FLOP, _STACK_START, Street.FLOP)
        ]
        a.turn[persona] = turn
        # River range: turn arrivals that flat-call the turn c-bet.
        rng = random.Random(4002)
        river = [
            s for s in turn
            if _continues_call(pack, rng, s[0], s[1][:4], a.pot_turn, a.stack_turn, Street.TURN)
        ]
        a.river[persona] = river
    return a


# --------------------------------------------------------------- fold curves


def _fold_curve(pack, spots, board_slice, pot_pre, stack, street, seed):
    """persona fold-to-bet over `spots` at each FLOP_FRACS size. Paired +
    seed-pinned (per-size seed) so cross-size comparisons are noise-stable."""
    out: dict[float, float] = {}
    for fi, frac in enumerate(FLOP_FRACS):
        to_call = round(frac * pot_pre, 2)
        pot = pot_pre + to_call
        legal = [_lf(), _lc(to_call), _lr(2 * to_call, stack)]
        rng = random.Random(seed + fi)
        folds = sum(
            sample_postflop_decision(
                pack, hole, board[:board_slice], legal, pot, stack, 1, rng,
                current_bet_to=to_call, street=street,
            ).action is ActionType.FOLD
            for hole, board in spots
        )
        out[frac] = folds / len(spots) if spots else float("nan")
    return out


