"""W3R-0 — arrival-range fold-to-bet-by-size measurement harness.

Spec:    docs/ai-dlc/specs/persona-realism-w3r-0.md
Tickets: docs/ai-dlc/tickets/persona-realism-w3r-0.md

WHY THIS EXISTS (the gap it closes)
-----------------------------------
The existing `fold_by_size` fixture (`tests/test_personas_postflop.py:455`)
measures fold-to-bet over a UNIFORM random deck — air-heavy, so it can only
prove slope/direction, never the archetype ABSOLUTE bands (station overbet
18–40%, fish 60–80%). Those §5 keystone magnitudes are gated nowhere. This
harness measures fold-rate over each persona's REALISTIC arrival range —
the hands it actually reaches the street with, generated by replaying its own
preflop (and street) policy — so W3R-2 can hard-prove the fish/station dial
fits rather than only their direction.

WHAT IT DOES (measurement only — ZERO bot behavior change)
----------------------------------------------------------
1. Arrival range (T1): canonical HU single-raised pot. Villain = RFI raiser,
   bot = `vs_rfi` caller/defender. Deal hands, replay `sample_preflop_action`
   per persona, keep ONLY the hands the persona flat-CALLS (3bet/raise hands
   EXCLUDED — a 3bettor is the aggressor and would be c-BETTING, not facing a
   c-bet, so counting them pollutes a single-raised-pot range and shifts the
   very bands we gate). That kept set is the flop arrival range.
2. Flop fold-to-bet (T2): fold-rate over the flop arrival range at
   {0.33, 0.5, 1.0, 1.5}× pot (mirrors `PRICE_FRACS`), paired + seed-pinned.
3. Turn/river continuation (T3): a scripted 2-player continuation sim (villain
   c-bets a fixed 2/3-pot each street; the bot responds) derives the turn then
   river CALL-continuing range, then measures fold-to-bet at the same buckets.
   Turn/river are MEASUREMENT-ONLY (no grounded absolute band yet).
4. Flop target bands (T4): grounded §5/F10 magnitudes as module constants +
   parametrized assertions — LIVE since W3R-2 fitted the fish/station dials
   (they shipped `pytest.mark.skip`-ed at W3R-0).

Everything is a PURE ADD: `sample_preflop_action` / `sample_postflop_decision`
are replayed READ-ONLY, no engine/JSON/conftest edits, no fixture re-records.

MANUAL INSPECTION
-----------------
Run:  cd backend && python -m tests.test_arrival_range_ftc
(or, inside a REPL, `print_curves()`) to dump the per-persona × street × size
fold curves. Pre-W3R-2 this showed the two leaks the T4 bands gate: the calling
station ~FLAT across sizes (size-blind) and the passive fish UNDER-folding the
overbet. Post-W3R-2 both rows rise across sizes inside the T4 bands.
"""

